// Builds supabase/schema.sql = ddl.sql + generated seed data.
// Usage: npm run build:schema
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { module1, module2 } from '../supabase/seed/modules-1-2.mjs';
import { module3, module4, module5, module6, module7, module8 } from '../supabase/seed/modules-3-8.mjs';
import { modules, tips, glossary } from '../supabase/seed/meta.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);

const lessonsByModule = { 1: module1, 2: module2, 3: module3, 4: module4, 5: module5, 6: module6, 7: module7, 8: module8 };

// Validate content before emitting SQL.
const problems = [];
for (const [num, lessons] of Object.entries(lessonsByModule)) {
  lessons.forEach((l, i) => {
    const where = `Module ${num} lesson ${i + 1} (${l.title})`;
    for (const f of ['title', 'what_is_it', 'why_it_matters', 'how_it_works', 'real_world_scenario', 'how_to_protect']) {
      if (!l[f] || !String(l[f]).trim()) problems.push(`${where}: missing ${f}`);
    }
    if (!Array.isArray(l.quiz) || l.quiz.length < 3 || l.quiz.length > 5) problems.push(`${where}: quiz must have 3–5 questions`);
    (l.quiz || []).forEach((qq, j) => {
      if (!qq.question || !Array.isArray(qq.options) || qq.options.length < 2) problems.push(`${where} Q${j + 1}: bad question/options`);
      if (!Number.isInteger(qq.answer) || qq.answer < 0 || qq.answer >= qq.options.length) problems.push(`${where} Q${j + 1}: answer index out of range`);
      if (!qq.explanation) problems.push(`${where} Q${j + 1}: missing explanation`);
    });
  });
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

let sql = `\n-- =====================================================================\n-- 8. SEED DATA (generated by scripts/build-schema.mjs — edit the files in supabase/seed/)\n-- =====================================================================\n\n`;

sql += `insert into public.modules (module_number, title, difficulty, description) values\n`;
sql += modules.map(([n, t, d, desc]) => `  (${n}, ${q(t)}, ${q(d)}, ${q(desc)})`).join(',\n');
sql += `\non conflict (module_number) do nothing;\n\n`;

let total = 0;
for (const [num, lessons] of Object.entries(lessonsByModule)) {
  sql += `-- Module ${num}\n`;
  sql += `insert into public.lessons (module_id, lesson_order, title, what_is_it, why_it_matters, how_it_works, real_world_scenario, how_to_protect, quiz_json)\nselect m.id, v.lesson_order, v.title, v.what_is_it, v.why_it_matters, v.how_it_works, v.real_world_scenario, v.how_to_protect, v.quiz_json::jsonb\nfrom public.modules m, (values\n`;
  sql += lessons
    .map((l, i) =>
      `  (${i + 1}, ${q(l.title)}, ${q(l.what_is_it)}, ${q(l.why_it_matters)}, ${q(l.how_it_works)}, ${q(l.real_world_scenario)}, ${q(l.how_to_protect)}, ${q(JSON.stringify(l.quiz))})`
    )
    .join(',\n');
  sql += `\n) as v(lesson_order, title, what_is_it, why_it_matters, how_it_works, real_world_scenario, how_to_protect, quiz_json)\nwhere m.module_number = ${num}\non conflict (module_id, lesson_order) do nothing;\n\n`;
  total += lessons.length;
}

sql += `insert into public.daily_tips (tip_text, category) values\n`;
sql += tips.map(([t, c]) => `  (${q(t)}, ${q(c)})`).join(',\n');
sql += `\non conflict (tip_text) do nothing;\n\n`;

sql += `insert into public.glossary_terms (term, definition, category) values\n`;
sql += glossary.map(([t, d, c]) => `  (${q(t)}, ${q(d)}, ${q(c)})`).join(',\n');
sql += `\non conflict (term) do nothing;\n\n`;

sql += `-- ---------------------------------------------------------------------\n-- 9. MAKE YOURSELF AN ADMIN (run separately after you sign up in the app)\n-- update public.profiles set role = 'admin' where email = 'you@example.com';\n-- ---------------------------------------------------------------------\n`;

const ddl = readFileSync(join(root, 'supabase/ddl.sql'), 'utf8');
writeFileSync(join(root, 'supabase/schema.sql'), ddl + sql);
console.log(`schema.sql written: ${modules.length} modules, ${total} lessons, ${tips.length} tips, ${glossary.length} glossary terms`);
